// brl_keygen - seller-side license tool. NEVER ship this or the private key.
//
//   brl_keygen genkeys <outDir>                 writes private.key + Source/PublicKey.h content
//   brl_keygen sign <private.key> <email> <id>  prints a license key for a customer
//   brl_keygen verify <public-key-string> <key>
#include "License.h"

using namespace juce;

int main (int argc, char* argv[])
{
    StringArray args;
    for (int i = 1; i < argc; ++i) args.add (argv[i]);
    auto usage = [] { std::cout << "usage:\n  brl_keygen genkeys <outDir>\n  brl_keygen sign <private.key> <email> <orderId>\n"
                                   "  brl_keygen verify <public-key-string> <key>\n"; return 1; };
    if (args.isEmpty()) return usage();

    if (args[0] == "genkeys" && args.size() == 2)
    {
        RSAKey pub, priv;
        RSAKey::createKeyPair (pub, priv, 1536);
        File dir (File::getCurrentWorkingDirectory().getChildFile (args[1]));
        dir.createDirectory();
        dir.getChildFile ("private.key").replaceWithText (priv.toString());
        dir.getChildFile ("public.key").replaceWithText (pub.toString());
        dir.getChildFile ("PublicKey.h").replaceWithText (
            "#pragma once\n// Generated by brl_keygen genkeys. Safe to ship (public half only).\n"
            "namespace brl::License { inline constexpr const char* kPublicKey = \"" + pub.toString() + "\"; }\n");
        std::cout << "Wrote private.key, public.key, PublicKey.h to " << dir.getFullPathName() << "\n"
                  << "Copy PublicKey.h into Source/ and keep private.key secret.\n";
        return 0;
    }
    if (args[0] == "sign" && args.size() == 4)
    {
        RSAKey priv (File::getCurrentWorkingDirectory().getChildFile (args[1]).loadFileAsString().trim());
        if (! priv.isValid()) { std::cerr << "bad private key\n"; return 1; }
        if ((args[2] + args[3]).getNumBytesAsUTF8() > 150) { std::cerr << "email + id too long\n"; return 1; }
        std::cout << brl::License::sign (priv, args[2], args[3]) << "\n";
        return 0;
    }
    if (args[0] == "verify" && args.size() == 3)
    {
        auto info = brl::License::verifyWith (RSAKey (args[1]), args[2]);
        std::cout << (info.valid ? "VALID  " + info.email + "  " + info.orderId : String ("INVALID")) << "\n";
        return info.valid ? 0 : 2;
    }
    return usage();
}
